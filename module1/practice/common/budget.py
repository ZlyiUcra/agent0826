"""
ЧЕЛЕНДЖ C · жорсткий ліміт витрат (друга половина челенджа).

Лежить у common/, хоч і належить челенджу C: ліміт перевіряє КОЖНА точка входу —
і основа, і всі челенджі, — тож у теці одного челенджа йому було б не місце.
Друга половина челенджа C, тести, живе там, де й має: challenges/c_tests.py.

Гранулярність зупинки — ОДИН ПРОГІН, і це свідоме рішення, а не спрощення.
Чому не «перед кожним викликом до API»: єдина точка втручання всередині циклу — `on_step`,
і його повернене значення `run_agent` ігнорує, а виняток з нього прошиває функцію
без словника результату (тобто «зупинка» перетворюється на падіння без outcome).
Зупиняти всередині циклу можна було б лише правкою `core/agent.py`, який спільний
для всіх модулів курсу і за домовленістю не змінюється.

Що це означає: ліміт не дає СТАРТУВАТИ наступний прогін, а вже початий
доходить до кінця. Перевитрата обмежена вартістю одного повного прогону.
Формулу «MAX_TURNS x MAX_TOKENS» тут навмисно не наводимо: вона обмежує лише
вихідні токени, а вхідні ростуть разом з історією і в неї не вкладаються.
"""

import core.agent as agent
from core.cost import PRICES, usd
from config import MODEL

# Ліміт за замовчуванням на один запуск скрипта. Перекривається змінною оточення
# PRACTICE_BUDGET_USD — саме так демонструється сценарій «бюджет вичерпано».
DEFAULT_LIMIT_USD = 0.10

# Скільки коштів резервується під один прогін. Це ОЦІНКА типового ланцюжка
# «пошук -> деталі» (три звернення до моделі), а не гарантована стеля.
# Резерв потрібен, бо порівнювати з лімітом саме витрачене — недостатньо:
# при нульових витратах будь-який, навіть копійчаний, ліміт пропустив би прогін,
# і зупинка спрацювала б уже ПІСЛЯ того, як гроші пішли.
RUN_RESERVE_USD = 0.02


def ensure_model_priced() -> None:
    """Падає голосно, якщо поточна модель відсутня в таблиці цін.

    Без цього `usd()` мовчки пропускає невідомий ключ і повертає нуль — тобто
    механізм, чиє призначення зупиняти витрати, не спрацював би НІКОЛИ, і ніхто
    б цього не помітив. Перевіряємо `config.MODEL` (уже після env-override), бо
    саме його передає `run_agent`; `MODEL_FAST` практика не викликає.

    Свідомо `raise SystemExit`, а не `assert`: `python -O` вирізає assert-и мовчки,
    і перевірка зникла б від одного прапорця інтерпретатора.
    """
    if MODEL not in PRICES:
        raise SystemExit(
            f"Модель '{MODEL}' відсутня в PRICES (core/cost.py).\n"
            f"  Вартість рахувалася б як нуль, і бюджетний ліміт не спрацював би.\n"
            f"  Відомі моделі: {', '.join(sorted(PRICES))}"
        )


def spent_usd() -> float:
    """Скільки вже витрачено в цьому процесі, за накопиченим `core.agent.USAGE`."""
    return usd(agent.USAGE["by_model"])


def check(limit_usd: float, reserve_usd: float = RUN_RESERVE_USD,
          extra_spent: float = 0.0) -> dict:
    """Чи можна запускати наступний прогін.

    Дозвіл дається, лише якщо на прогін лишається зарезервована сума. Тобто ліміт
    зупиняє ДО витрати, а не після неї.

    `extra_spent` потрібен там, де один процес робить кілька прогонів і скидає
    `USAGE` між ними заради чистих поцененарійних чисел (`practice/base/demo.py`).
    Лічильник тоді показує лише поточну сцену, а бюджет мусить бачити суму всіх.
    """
    spent = spent_usd() + extra_spent
    left = round(limit_usd - spent, 6)
    return {"ok": left >= reserve_usd, "spent": spent, "limit": limit_usd,
            "left": left, "reserve": reserve_usd}


def refusal_text(state: dict) -> str:
    """Пояснення для клієнта і для лога — без евфемізмів про «технічні роботи»."""
    return ("Зупиняюсь: на прогін не лишилось бюджету "
            f"(витрачено ${state['spent']:.4f} з ліміту ${state['limit']:.4f}, "
            f"вільно ${state['left']:.4f}, потрібен резерв ${state['reserve']:.4f}). "
            "Жодного звернення до моделі не зроблено. "
            "Підніміть PRACTICE_BUDGET_USD або почніть новий процес.")
