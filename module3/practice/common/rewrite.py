"""
СПІЛЬНЕ · переформулювання запиту, коли знайшлося мало.

Необов'язковий пункт картки: «якщо знайшлось мало — хай агент переформулює запит
і спробує ще раз». Тут це не побажання агентові, а механізм усередині інструмента:
`search_docs` сам помічає бідний результат, сам переписує запит і сам шукає вдруге.

ЧОМУ НЕ ЛИШИТИ ЦЕ АГЕНТОВІ

Агент і так переформулює, коли вважає за потрібне: у прогоні `proxy` він робить
три-шість пошуків поспіль, щоразу міняючи слова. Але це його власне рішення, і воно
не спрацьовує саме там, де потрібне — коли пошук повернув один слабкий фрагмент,
модель радше візьме те, що дали, ніж запідозрить, що шукала не тими словами.
Механізм не покладається на здогад: умова спрацювання описана нижче і рахується
з самих оцінок пошуку.

ЩО ВВАЖАЄТЬСЯ «МАЛО»

Дві умови, і достатньо однієї: фрагментів, що подолали нижню межу схожості, менше за
`MIN_HITS`, або найкращий із них зачепився слабко — нижче за `CONFIDENT`.

Друга умова з'явилася після виміру, і без неї механізм був би мертвим кодом.
Нижня межа `e5` стоїть майже на середньому косинусі по всіх фрагментах, тож крізь неї проходить
приблизно половина фрагментів і кількість знайденого до трьох не спадає ніколи.
Правило «менше трьох» з цією моделлю не спрацювало б жодного разу.

`CONFIDENT` виміряно так: вісім запитів, поставлених людськими словами, і ті самі
запити після переписування. У `e5` найкращий фрагмент людських запитів лягав у проміжок
0.831–0.883, переписаних — 0.869–0.900; у `bge` — 0.671–0.773 проти 0.755–0.855. Проміжки в
обох трохи перекриваються, і це не страшно. Умова не стверджує, що відповідь
знайдена чи не знайдена; вона вирішує лише, чи варто спробувати ще раз. Ціна
хибного спрацювання — один виклик Haiku, бо з двох наборів однаково береться
кращий.

ЧОГО МЕХАНІЗМ НЕ ЧІПАЄ І ЧОМУ

Порожній результат не переписується. Це виглядає нелогічно — здавалося б, саме
там друга спроба найпотрібніша, — але вимір показав протилежне.

На запиті «What is the capital of France?» Haiku відмовився переписувати і
відповів текстом «I appreciate the test, but this question isn't about JavaScript
or ECMAScript...». Цей текст пішов у пошук як запит. Слова «JavaScript» і
«ECMAScript» у ньому є, документи всі про JavaScript, і оцінка вийшла 0.843 —
вище за межу 0.80. Те саме сталося з питанням про борщ: 0.841.

Тобто відмова допоміжної моделі перетворилася на дані, і агент отримав би три
фрагменти там, де раніше не отримував нічого. Маючи текст на руках, він узявся б
відповідати — тобто заради необов'язкового пункту картки перестав би виконуватися
третій обов'язковий.

Тому переписування вмикається лише тоді, коли перший пошук щось таки знайшов.
Порожньо лишається порожнім, і шлях до відмови незмінний.

Другий запобіжник на той самий випадок — `_looks_like_refusal`. Переписаний
запит має бути коротким рядком у термінах специфікації; багатослівна відповідь
від першої особи — це не запит, і в пошук вона не йде.

ЧИМ ПЕРЕПИСУЄМО

Дешевою моделлю з каскаду — `MODEL_FAST` у `config.py`, це Haiku. Робота проста:
взяти людське формулювання і назвати те саме словами специфікації. Дорога модель
тут не потрібна, і саме для такого каскад і заведений. Виклик іде через
`core.agent.ask` з `temperature=0`, тобто на однаковий запит дає однакове
переписування — інакше два прогони того самого сценарію не можна було б
порівнювати.

Імпорт `core.agent` навмисно захований усередину функції. На рівні модуля він
потягнув би `config`, а той падає без ключа в `.env` — і безкоштовні прогони
`compare` та `threshold`, яким жодна модель Anthropic не потрібна, перестали б
запускатися взагалі.

ЩО ПОВЕРТАЄТЬСЯ

Кращий з двох наборів, і ознака того, що друга спроба була. Кращий визначається
кількістю знайденого, а при рівності — оцінкою першого фрагмента. Якщо друга
спроба нічого не додала, лишається перша: переписування не має права зробити
результат гіршим.
"""

import os

# Скільки фрагментів має подолати межу, щоб результат вважався достатнім.
# Три — це стільки, скільки інструмент і просить у пошуку (k=3); менше означає,
# що частину відсікла нижня межа.
MIN_HITS = 3

# Наскільки міцно має зачепитися найкращий фрагмент, щоб друга спроба була зайвою.
# Значення для кожної моделі своє, бо косинуси в них живуть у різних діапазонах.
# Обидва виміряно на тих самих восьми запитах: людські формулювання проти
# переписаних. Числа й самі формулювання — у practice/README.md модуля 2.
CONFIDENT = {"e5": 0.87, "bge": 0.78}

# Довший за це переписаний запит майже напевно не запит, а міркування моделі.
MAX_REWRITE_CHARS = 160

# Початки, з яких допоміжна модель починає, коли відмовляється переписувати.
_REFUSAL_OPENERS = ("i ", "sorry", "this question", "unfortunately", "as an ai")

REWRITE_PROMPT = (
    "You turn a plain-language question about JavaScript into a search query "
    "phrased the way the ECMAScript specification itself phrases things.\n"
    "The specification calls a stand-in object a Proxy, calls the parent of an "
    "object its prototype, describes behaviour through internal methods written "
    "in double brackets such as [[Get]] and [[OwnPropertyKeys]], and names methods "
    "in full, such as String.prototype.replace.\n"
    "Reply with the rewritten query alone: no quotes, no explanation, one line."
)


def confident_bar() -> float:
    """Планка впевненості для поточної моделі ембедингів."""
    from .vectors import MODEL_KEY
    return CONFIDENT[MODEL_KEY]


def _looks_like_refusal(text: str) -> bool:
    """Переписаний запит, який насправді є відповіддю моделі, а не запитом."""
    low = text.strip().lower()
    return len(text) > MAX_REWRITE_CHARS or low.startswith(_REFUSAL_OPENERS)


def enabled() -> bool:
    """Механізм вмикається змінною оточення PRACTICE_REWRITE=1.

    За замовчуванням вимкнений, щоб прогони без нього лишалися порівнюваними з
    тими, що вже записані в README, і щоб безкоштовні прогони лишалися безкоштовними.
    """
    return os.getenv("PRACTICE_REWRITE", "0") not in ("0", "", "no", "false")


def reformulate(query: str) -> str:
    """Переписує запит термінами специфікації. Порожній рядок — переписати не вдалось."""
    from core.agent import ask

    try:
        new = ask(REWRITE_PROMPT, query, max_tokens=120, fast=True, temperature=0.0)
    except Exception:
        # Збій допоміжного виклику не має валити пошук: краще віддати те, що
        # знайшлося з першого разу, ніж не віддати нічого.
        return ""
    new = new.strip().strip('"').splitlines()[0] if new.strip() else ""
    if not new or new.lower() == query.lower() or _looks_like_refusal(new):
        return ""
    return new
