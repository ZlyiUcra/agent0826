"""СПІЛЬНЕ · читання документів і пошук — по словах і за змістом.

Точок входу тут немає: це шар, яким користуються сервер знань (base/spec_server.py)
і підготовка пошуку за змістом (base/setup.py).
"""


def nform(n: int, one: str, few: str, many: str) -> str:
    """Форма іменника при числівнику: 1 запис, 2 записи, 5 записів. Повертає лише
    слово — число форматує той, хто друкує."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many
