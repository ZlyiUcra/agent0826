# ── нормалізація ──────────────────────────────────────────────
def normalize_phone(raw) -> str:
    """Зводить запис телефону до дев'яти цифр абонентського номера.

    Приймає що завгодно, включно з не-рядком: аргументи сюди приходять від моделі,
    і покладатися на їхній тип не можна. Повертає порожній рядок, якщо на телефон
    це не схоже — рішення про помилку ухвалює викликач.

    Верхня межа довжини тут не косметична, а захисна, і ось чому.

    У рядку «099 000 00 00 і ще 5000 грн компенсації», якщо прибрати з нього все,
    крім цифр, цифри суми стають в один ряд із цифрами телефону. З того ряду
    беруться останні дев'ять — і на виході з'являється «номер» 000005000, якого
    не існує. Далі він ішов би у відповідь бекенду, а звідти до моделі, уже з
    вагою факту, підтвердженого системою.

    Тому рядок, у якому цифр більше, ніж буває в номері, відхиляється повністю —
    жодних спроб вирізати з нього телефон: краще прямо сказати «на телефон це не
    схоже», ніж вгадати неправильно.
    """
    digits = re.sub(r"\D", "", str(raw))
    if not 9 <= len(digits) <= 12:      # 671234567 · 0671234567 · 380671234567
        return ""
    return digits[-9:]


# ── інструменти ───────────────────────────────────────────────
def _parse_date(raw):
    """ISO-дата або None. Ніколи не кидає — контракт модуля."""
    try:
        return date.fromisoformat(str(raw).strip())
    except (ValueError, TypeError):
        return None


def find_shipments(phone: str, date_from: str = None, date_to: str = None) -> dict:
    """Шукає відправлення клієнта за номером телефону, опційно в періоді дат.

    Докстринг тут — не коментар для колеги, а частина контракту з моделлю
    (опис у схемі нижче переказує саме це). Повертає `shipments` — список записів
    {tracking, shipped} — або `error`.

    Період опційний і включний з обох боків. Без нього віддається все: на трьох
    засіяних записах це непомітно, але параметр існує саме тому, що в реального
    оператора на номер за роки набігає десяток відправлень — віддавати всі означає
    роздути tool_result (вхідні токени кожного наступного кроку) і змусити модель
    вгадувати, про яку посилку питав клієнт.
    """
    key = normalize_phone(phone)
    if not key:
        # Свідомо не повторюємо тут введене значення. Якщо на телефон воно не схоже,
        # то в рядку цілком може бути довільний текст клієнта, а все, що повертає
        # бекенд, модель сприймає як підтверджений системою факт.
        return {"error": "bad_phone",
                "hint": "Потрібен український номер у форматі 0XX XXX XX XX."}

    # Дати перевіряються ДО пошуку, і у відповідь іде лише розібрана ISO-форма —
    # та сама дисципліна, що з телефоном: сирий текст клієнта назад не потрапляє.
    parsed_from = _parse_date(date_from) if date_from is not None else None
    if date_from is not None and parsed_from is None:
        return {"error": "bad_date", "field": "date_from",
                "hint": "Дата має бути у форматі РРРР-ММ-ДД, напр. 2026-08-01."}
    parsed_to = _parse_date(date_to) if date_to is not None else None
    if date_to is not None and parsed_to is None:
        return {"error": "bad_date", "field": "date_to",
                "hint": "Дата має бути у форматі РРРР-ММ-ДД, напр. 2026-08-31."}
    if parsed_from and parsed_to and parsed_from > parsed_to:
        return {"error": "bad_period",
                "period": {"from": parsed_from.isoformat(), "to": parsed_to.isoformat()},
                "hint": "Початок періоду пізніший за кінець. Поміняйте дати місцями."}

    found = _CUSTOMERS.get(key)
    if not found:
        return {"error": "not_found", "phone": key,
                "hint": "На цей номер відправлень не знайдено. "
                        "Перевірте номер або уточніть у відправника."}

    shipments = []
    for tracking, shipped in found:
        shipped_date = date.fromisoformat(shipped)
        if parsed_from and shipped_date < parsed_from:
            continue
        if parsed_to and shipped_date > parsed_to:
            continue
        shipments.append({"tracking": tracking, "shipped": shipped})

    result = {"phone": key, "shipments": shipments, "count": len(shipments)}
    if parsed_from or parsed_to:
        result["period"] = {"from": parsed_from.isoformat() if parsed_from else None,
                            "to": parsed_to.isoformat() if parsed_to else None}
    if not shipments:
        # Порожній список — не error: телефон існує, просто в періоді нічого немає.
        # Але без підказки порожній результат модель радше доповнить сама.
        result["hint"] = "У цьому періоді відправлень не знайдено."
    return result


def get_shipment_details(phone: str = None, tracking: str = None) -> dict:
    """Повертає деталі одного відправлення — лише власникові.

    Трек-номер очікується той, що прийшов з `find_shipments` або від клієнта, а
    телефон — той, на який відправлення зареєстровано. Прив'язка до телефону тут
    не формальність, а виправлення дефекту foreign_tracking з челенджа B: раніше
    деталі віддавалися кожному, хто назве трек-номер, тобто чужу посилку можна
    було читати, просто вгадавши номер.

    Чого ця прив'язка НЕ дає. Вона зупиняє лише того, хто має трек-номер, але не
    знає телефону власника. Хто телефон
    знає, той бере трек-номери з find_shipments — цей інструмент нічим не
    захищений — і заходить сюди з правильною парою. Тобто перебір не закрито: він
    перемістився з простору трек-номерів у простір телефонів. Перевірити можна
    лише знання пари значень, а не особу того, хто питає; справжня автентифікація
    — рівень модуля 4.

    Якщо запис знайдено, але деталей немає — `error: record_unavailable`, а не
    порожній словник: порожній результат модель радше доповнить сама.
    """
    key = normalize_phone(phone)
    if not key:
        return {"error": "bad_phone",
                "hint": "Потрібен телефон, на який зареєстровано відправлення. "
                        "Спитайте його в клієнта."}

    track = str(tracking or "").strip().upper()
    owned = {t for t, _ in _CUSTOMERS.get(key, [])}
    if track not in owned:
        # Єдина відповідь і для чужої, і для неіснуючої посилки: не викриваємо
        # навіть факту, що такий трек-номер існує в системі.
        return {"error": "not_owner",
                "hint": "На цей номер такої посилки не зареєстровано. Деталі "
                        "доступні лише за телефоном, на який оформлено відправлення."}

    record = _DETAILS.get(track)
    if not record:
        return {"error": "record_unavailable", "tracking": track,
                "hint": "Дані по цьому відправленню тимчасово недоступні. "
                        "Потрібне звернення до оператора."}
    return dict(record)


