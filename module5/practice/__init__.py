# Типовий набір документів — найширший із наявних: уся ECMA-262 плюс ECMA-402,
# 404, 414 і вільні документи, на які спирається 402. Перемикається змінною
# PRACTICE_DOCS («full» — лише 262, «core» — вісімнадцять розділів навколо типу
# Object). Рішення стоїть тут, а не в сервері, щоб і сервер, і підготовка, і
# перевірки бачили один і той самий набір. setdefault, а не присвоєння: названий
# у оточенні набір лишається за власником.
