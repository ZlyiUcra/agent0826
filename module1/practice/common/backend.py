# Робочий набір за замовчуванням. Ім'я лишається старим, бо на нього спираються
# і практика, і тести.
PRACTICE_SCHEMAS = SCHEMAS_TUNED

# Власний аналог курсового BASIC: явний список того, що дозволено агенту практики.
# Права живуть біля бекенда, окремо від циклу — той самий патерн, що CAPABILITIES,
# лише для іншого споживача.
PRACTICE_TOOLS = ["find_shipments", "get_shipment_details"]


def tools(variant: str = None) -> list:
    """Список схем для передачі в `run_agent(tools=...)`.

    Варіант описів обирається аргументом або змінною оточення PRACTICE_SCHEMAS
    ("tuned" за замовчуванням, "naive" — для експерименту челенджа A). Реалізації
    при цьому ті самі: міняється лише текст, який бачить модель.
    """
    name = variant or os.getenv("PRACTICE_SCHEMAS", "tuned")
    schemas = SCHEMA_VARIANTS.get(name)
    if schemas is None:
        raise SystemExit(f"Невідомий набір описів '{name}'. "
                         f"Доступні: {', '.join(sorted(SCHEMA_VARIANTS))}")
    return [schemas[n] for n in PRACTICE_TOOLS]
